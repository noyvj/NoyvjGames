"""Label every open item in planning/TODO.md and planning/TODO-NEXT.md with who can do it.

    python local-ai/label_todo.py            show the counts and a few examples
    python local-ai/label_todo.py --write    write the labels (end of each open line) and the legend block

A label sits at the end of an open item's line, for example "... [local AI: yes]". Rerunning replaces the
old labels, so it is safe after adding or ticking items. The progress script (scripts/todo-progress.py)
reads only the "- [ ]" box at the start of a line, so the labels do not change its counts.

The rules reuse make_todo_tasks.py (which game an item is about; what the local AI cannot do: QA, owner
input, backend, live web data, site-wide or shared files) and sort_queue.py (the words that mark a big
feature), plus three facts about the repo: a game folder with no code yet, and the six games whose files are
too big for the local model.
"""
import re
import sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import make_todo_tasks as mt  # noqa: E402
import sort_queue as sq  # noqa: E402

ROOT = HERE.parent
LISTS = [ROOT / "planning" / "TODO.md", ROOT / "planning" / "TODO-NEXT.md"]
TOO_BIG = set()   # SP-1 split every big game's files on 2026-10-17 (Loop and Drift: see local-ai/FOR-CLAUDE.md)
OVERRIDES_FILE = HERE / "label-overrides.txt"   # written by scripts/build_incoming_tasks.py from the LA-8 notes
MANUAL_OVERRIDES_FILE = HERE / "label-overrides-manual.txt"   # hand-kept: items an audit showed the local AI must not take


def load_overrides():
    out = {}
    for f in (OVERRIDES_FILE, MANUAL_OVERRIDES_FILE):   # the manual file wins
        if f.exists():
            for line in f.read_text(encoding="utf-8").splitlines():
                if line.strip() and not line.startswith("#") and "|" in line:
                    item, tag = (x.strip() for x in line.split("|", 1))
                    out[item] = tag
    return out


OVERRIDES = load_overrides()
OPEN = re.compile(r"^(\s*- \[ \] ([A-Z0-9][A-Z0-9-]*[A-Z0-9]):?\s*(?:\((small|big)\)\s*)?)(.*?)(\s*\[(?:local AI|Claude|needs you|on hold)[^\]]*\])?\s*$")
START = "<!-- LOCAL-AI-LABELS:START (generated by local-ai/label_todo.py, do not edit) -->"
END = "<!-- LOCAL-AI-LABELS:END -->"

LEGEND = [
    "**Who can do each open item.** Each open line ends with a label (rerun `python local-ai/label_todo.py --write` after adding items):",
    "- `[local AI: yes]`: the local AI on the Windows laptop can do it now (one game, small enough). These run first.",
    "- `[local AI: after split]`: too big for one local-AI task. Noy2 splits it into small exact steps first (`local-ai/FOR-NOY2.md`, item 1).",
    "- `[local AI: after file split]`: the game's own files are too big for the local model. Noy2 splits the game's code first (FOR-NOY2.md, item 5).",
    "- `[local AI: in steps]`: Noy2 cut it into small exact steps (`local-ai/incoming-tasks.txt`); the runner queues the steps, not the item.",
    "- `[local AI: after the game is built]`: the game folder has no code yet. Its milestones come first.",
    "- `[Claude: ...]`: needs a Claude session (site-wide or shared files, backend, live web data, hub registration, or not tied to one game).",
    "- `[needs you]`: waits on your answer, account or decision. `[on hold]`: the QA pass, on hold until closing time.",
]


def has_code(game):
    folder = ROOT / "games" / game
    return any(folder.glob("*.py")) or any(folder.glob("*.js"))


def label(section, item, size, text):
    low = (section + " " + text).lower()
    reason = next((why for pattern, why in mt.SKIP if re.search(pattern, low if pattern != "^qa" else section.lower())), None)
    if item.endswith("-add") or re.search(r"when you have (answered|picked)", low):
        return "[needs you]"   # placeholders that wait on the owner's answers on the ideas sheet
    if reason == "QA (on hold)":
        return "[on hold]"
    if reason == "needs the owner":
        return "[needs you]"
    if reason == "backend / other players":
        return "[Claude: backend]"
    if reason == "live web data":
        return "[Claude: live web data]"
    if reason == "site-wide / shared":
        return "[Claude: site-wide]"
    if "register in the hub" in low:
        return "[Claude: hub registration]"
    game = mt.game_of(section, text)
    if not game or not (ROOT / "games" / game).is_dir():
        return "[Claude: not one game]" if not reason else "[local AI: after the game is built]"
    if game in TOO_BIG:
        return "[local AI: after file split]"
    if reason == "new-game milestone":
        return "[local AI: after split]"
    if not has_code(game):
        return "[local AI: after the game is built]"
    hard = len(re.findall(sq.HARD, text.lower()))
    if size == "big" or hard >= 2 or len(text) > 420:
        return "[local AI: after split]"
    return "[local AI: yes]"


def process(path, write):
    raw = path.read_bytes()
    nl = "\r\n" if b"\r\n" in raw else "\n"
    lines = raw.decode("utf-8").splitlines()
    counts, examples, section, out = Counter(), {}, "", []
    for line in lines:
        if line.startswith("## "):
            section = line[3:].strip()
        m = OPEN.match(line)
        if m:
            head, item, size, text = m.group(1), m.group(2), m.group(3), m.group(4)
            tag = OVERRIDES.get(item) or label(section, item, size, text)
            counts[tag] += 1
            examples.setdefault(tag, f"{item}: {text[:90]}")
            line = f"{head}{text} {tag}"
        out.append(line)
    text = nl.join(out) + nl
    block = nl.join([START] + LEGEND + ["", "Open items now: " + ", ".join(f"{k} {v}" for k, v in counts.most_common()) + ".", END])
    if START in text:
        text = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: block, text, count=1, flags=re.S)
    else:
        anchor = "<!-- PROGRESS-CHART:END -->"
        at = text.find(anchor)
        at = text.find(nl, at) + len(nl) if at >= 0 else text.find(nl + nl) + len(nl)
        text = text[:at] + nl + block + nl + text[at:]
    if write:
        path.write_bytes(text.encode("utf-8"))
    return counts, examples


def main(argv):
    total = Counter()
    for path in LISTS:
        counts, examples = process(path, "--write" in argv)
        total += counts
        print(f"{path.name}: " + ", ".join(f"{k} {v}" for k, v in counts.most_common()))
        for tag, ex in examples.items():
            print(f"    {tag:40} e.g. {ex}")
    print("both lists: " + ", ".join(f"{k} {v}" for k, v in total.most_common()))
    if "--write" in argv:
        print("labels written.")


if __name__ == "__main__":
    main(sys.argv[1:])
