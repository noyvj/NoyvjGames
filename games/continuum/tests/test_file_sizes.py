"""Continuum is split into small files so a small local AI (it holds about 24k tokens and has to read a whole file to
edit it) can edit them. These tests keep it that way: no editable file passes about 14,000 estimated tokens (bytes / 4).
The generated Desktop page, the notes file (CLAUDE.md) and the data files are exempt; index.html is the page's markup
(one big block of real markup, no seam to cut) and has its own documented cap. See "File map" in CLAUDE.md."""
from pathlib import Path

GAME_DIR = Path(__file__).resolve().parent.parent
MAX_TOKENS = 14_000
# index.html is about 67 KB of markup once every script and stylesheet is a separate file (the panels, the settings window,
# the Desktop-shared ids). It is the one file allowed above the usual limit, with a hard cap so it cannot keep growing.
CAPS = {"index.html": 17_500}
EDITABLE_SUFFIXES = {".py", ".js", ".css", ".html", ".md", ".txt"}
# pc.html is generated by scripts/generate-pc-pages.py from index.html; CLAUDE.md is documentation for the main session.
EXEMPT = {"pc.html", "CLAUDE.md"}
SKIP_DIRS = {"__pycache__", ".pytest_cache"}


def _editable_files():
    for path in sorted(GAME_DIR.rglob("*")):
        if not path.is_file() or path.suffix not in EDITABLE_SUFFIXES:
            continue
        if SKIP_DIRS & set(path.relative_to(GAME_DIR).parts) or path.name in EXEMPT:
            continue
        yield path


def test_no_editable_file_is_over_the_token_limit():
    too_big = []
    for path in _editable_files():
        rel = path.relative_to(GAME_DIR)
        tokens = len(path.read_bytes()) // 4
        if tokens > CAPS.get(rel.as_posix(), MAX_TOKENS):
            too_big.append(f"{rel}: about {tokens} tokens")
    assert not too_big, (
        "Split these files (see 'File map' in CLAUDE.md for the recipe), the AI cannot read a file this big: "
        + "; ".join(too_big)
    )


def test_the_check_sees_the_files_it_should():
    names = {path.name for path in _editable_files()}
    assert {"game.py", "sim.py", "research.py", "index.html", "style.css", "boot.js", "render3d.js",
            "continuum_runstate.py", "continuum_sim_city.py"} <= names
    assert "pc.html" not in names and "CLAUDE.md" not in names


def test_the_pages_load_the_split_stylesheets_in_order():
    import re

    for page in ("index.html", "pc.html"):
        html = (GAME_DIR / page).read_text(encoding="utf-8")
        links = re.findall(r'<link rel="stylesheet" href="(style[^"]*\.css)"', html)
        assert links == ["style-1-base.css", "style-2-console.css", "style.css"], page


def test_the_pages_load_the_scene_file_before_the_renderer():
    for page in ("index.html", "pc.html"):
        html = (GAME_DIR / page).read_text(encoding="utf-8")
        assert html.index('src="render3d-scenes.js"') < html.index('src="render3d.js"') < html.index('src="boot.js"'), page
