"""Keeps Canopy's files small enough for the personal AI, which holds about 24k tokens and has to read a whole file to
edit it. Size is estimated as bytes divided by 4. The generated Desktop page, the notes file and data files are exempt;
index.html is the page's markup (one big block of real markup, no seam to cut) and has its own documented cap."""
import re
from pathlib import Path

GAME_DIR = Path(__file__).resolve().parent.parent
MAX_TOKENS = 14_000
# index.html is about 59 KB (14,700 tokens) of markup once every script and stylesheet is a separate file: the grid, stats,
# stakeholder, regions, Forest Lab, layout editor, contracts, vault, expedition and summary panels are all real static markup
# that the tests and the shared scripts look up by id, so there is no seam to cut. It is the one file allowed above the usual
# limit, with a hard cap so it cannot keep growing.
CAPS = {"index.html": 15_000}
EDITABLE_SUFFIXES = {".py", ".js", ".css", ".html"}
EXEMPT = {"pc.html"}  # generated by scripts/generate-pc-pages.py from index.html, never edited by hand
SKIP_DIRS = {"__pycache__", ".pytest_cache"}


def _editable_files():
    for path in sorted(GAME_DIR.rglob("*")):
        if not path.is_file() or path.suffix not in EDITABLE_SUFFIXES:
            continue
        if SKIP_DIRS & set(path.relative_to(GAME_DIR).parts):
            continue
        if path.name in EXEMPT:
            continue
        yield path


def test_no_editable_file_is_over_the_token_limit():
    too_big = []
    for path in _editable_files():
        rel = path.relative_to(GAME_DIR)
        tokens = len(path.read_bytes().replace(b"\r\n", b"\n")) // 4
        if tokens > CAPS.get(rel.as_posix(), MAX_TOKENS):
            too_big.append(f"{rel}: about {tokens} tokens")
    assert not too_big, (
        "Split these files (see 'File map' in CLAUDE.md for the recipe), the AI cannot read a file this big: "
        + "; ".join(too_big)
    )


def test_the_check_sees_the_files_it_should():
    names = {path.name for path in _editable_files()}
    assert {"game.py", "index.html", "style.css", "boot.js", "canopy_runstate.py"} <= names
    assert "pc.html" not in names


def test_the_pages_load_the_split_stylesheets_in_order():
    for page in ("index.html", "pc.html"):
        html = (GAME_DIR / page).read_text(encoding="utf-8")
        links = re.findall(r'<link rel="stylesheet" href="(style[^"]*\.css)"', html)
        assert links == ["style-1-base.css", "style-2-visuals.css", "style-3-features.css", "style.css"], page
