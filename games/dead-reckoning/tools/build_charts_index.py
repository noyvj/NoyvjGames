"""Writes charts_index.py: the small always-loaded index of the campaign (chapter -> chart ids and names, chart -> hazard ids).

    python3 tools/build_charts_index.py            # rewrite charts_index.py
    python3 tools/build_charts_index.py --check    # exit 1 if it is out of date

The chart bodies of chapters 2 to 7 are lazy packs (modules.json), so the chooser, the progress totals, the save cleaner and the
achievements read this index instead of the chart modules. Run it whenever a chart is added, renamed or given a hazard."""

import importlib
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(HERE))

CHAPTER_MODULES = [("open", "charts_open"), ("wind", "charts_wind"), ("fixes", "charts_fixes"), ("fog", "charts_fog"),
                   ("tides", "charts_tides"), ("compass", "charts_compass"), ("ships", "charts_two")]


def build():
    index = {}
    hazards = {}
    for chapter_id, module in CHAPTER_MODULES:
        charts = importlib.import_module(module).CHARTS
        index[chapter_id] = [[c["id"], c["name"]] for c in charts]
        for c in charts:
            hazards[c["id"]] = sorted(h["id"] for h in c.get("hazards", ()))
    lines = ['"""Dead Reckoning -- the always-loaded index of the campaign. GENERATED by tools/build_charts_index.py: do not edit by hand.',
             '', 'INDEX: chapter id -> [[chart id, chart name], ...] in play order. HAZARDS: chart id -> its hazard ids (the save cleaner uses',
             'them). The chart bodies of chapters 2 to 7 are lazy packs; see charts.py and modules.json."""', '', 'INDEX = {']
    for chapter_id, rows in index.items():
        lines.append("    %r: [" % chapter_id)
        for cid, name in rows:
            lines.append("        [%r, %r]," % (cid, name))
        lines.append("    ],")
    lines.append("}")
    lines.append("")
    lines.append("HAZARDS = {")
    for cid, ids in hazards.items():
        lines.append("    %r: %r," % (cid, ids))
    lines.append("}")
    return "\n".join(lines) + "\n"


def main(argv):
    text = build()
    target = HERE / "charts_index.py"
    if "--check" in argv:
        return 0 if target.is_file() and target.read_text(encoding="utf-8") == text else 1
    target.write_text(text, encoding="utf-8")
    print("wrote %s (%d bytes)" % (target.name, len(text)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
