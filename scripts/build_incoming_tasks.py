#!/usr/bin/env python3
"""Build the files the Windows session reads from the per-game drafts in local-ai/incoming/ (LA-8).

    python3 scripts/build_incoming_tasks.py            write local-ai/incoming-tasks.txt and local-ai/label-overrides.txt
    python3 scripts/build_incoming_tasks.py --check    exit 1 if either file is out of date

Input: local-ai/incoming/<game>.txt (queue lines, linted by scripts/lint_incoming_tasks.py) and
local-ai/incoming/<game>-notes.md, whose "C list" table rows (`| ITEM text | `[label]` | reason |`) say an item is NOT for the
local AI and which label it should carry, and whose "A list" bullets (`- ITEM ...`) say an item is small enough to relabel
`[local AI: yes]`. Output:
  local-ai/incoming-tasks.txt   all the games' lines, grouped by game (refresh_queue.py picks this up)
  local-ai/label-overrides.txt  `ITEM | [label]` lines that local-ai/label_todo.py applies over its own rules
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INC = ROOT / "local-ai" / "incoming"
OUT_TASKS = ROOT / "local-ai" / "incoming-tasks.txt"
OUT_OVER = ROOT / "local-ai" / "label-overrides.txt"
STATUS = ROOT / "local-ai" / "steps-status.txt"   # hand-kept: `done: chain:X:N, ...` and `redo: chain:X:N, ...` lines from audits
ID = r"[A-Z0-9][A-Z0-9-]*[A-Z0-9]"


def overrides_from_notes(path):
    out, section = {}, ""
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("## "):
            section = line[3:].strip().lower()
            continue
        if section.startswith("a list"):
            m = re.match(rf"^- ({ID})\b", line)
            if m:
                out[m.group(1)] = "[local AI: yes]"
        m = re.match(rf"^\|\s*({ID})\b[^|]*\|\s*`(\[[^`\]]+\])`\s*\|", line)
        if m:
            out[m.group(1)] = m.group(2)
    return out


def chain_items(path):
    """Items whose `# replaces:` group is made of chain steps: their TODO label becomes [local AI: in steps]."""
    out, ids = {}, []
    for line in path.read_text(encoding="utf-8-sig").splitlines():
        m = re.match(r"^#\s*replaces:\s*(.+)$", line)
        if m:
            ids = [x.strip() for x in m.group(1).split(",") if x.strip()]
            continue
        if re.match(r"^\S+\s*\|\s*chain:", line):
            for i in ids:
                out[i] = "[local AI: in steps]"
    return out


def build():
    tasks = ["# Generated by scripts/build_incoming_tasks.py from local-ai/incoming/*.txt: do not edit by hand.",
             "# `# replaces:` lines name the whole items their steps replace (local-ai/refresh_queue.py)."]
    if STATUS.exists():
        for line in STATUS.read_text(encoding="utf-8").splitlines():
            m = re.match(r"^(done|redo):\s*(.+)$", line.strip())
            if m:
                tasks.append(f"# {m.group(1)}: {m.group(2)}")
    over = {}
    for f in sorted(INC.glob("*.txt")):
        body = [l for l in f.read_text(encoding="utf-8-sig").splitlines() if l.strip()]
        if not any(l.strip() and not l.startswith("#") for l in body):
            continue
        tasks.append("")
        tasks.extend(body)
    for f in sorted(INC.glob("*-notes.md")):
        over.update(overrides_from_notes(f))
    for f in sorted(INC.glob("*.txt")):
        over.update(chain_items(f))
    lines = ["# Generated by scripts/build_incoming_tasks.py from local-ai/incoming/*-notes.md: do not edit by hand.",
             "# ITEM | [label]  (applied over the rules of local-ai/label_todo.py)"]
    lines += [f"{k} | {v}" for k, v in sorted(over.items())]
    return "\n".join(tasks) + "\n", "\n".join(lines) + "\n"


def main():
    tasks, over = build()
    if "--check" in sys.argv:
        ok = OUT_TASKS.exists() and OUT_TASKS.read_text(encoding="utf-8") == tasks and OUT_OVER.exists() and OUT_OVER.read_text(encoding="utf-8") == over
        sys.exit(0 if ok else 1)
    OUT_TASKS.write_text(tasks, encoding="utf-8")
    OUT_OVER.write_text(over, encoding="utf-8")
    print(f"wrote {OUT_TASKS.name} ({tasks.count(chr(10))} lines) and {OUT_OVER.name} ({over.count(chr(10)) - 2} overrides)")


if __name__ == "__main__":
    main()
